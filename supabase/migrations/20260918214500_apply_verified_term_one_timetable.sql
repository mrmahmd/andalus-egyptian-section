-- Publication is automatic when every required timetable slot has non-empty work.
create or replace function private.refresh_weekly_plan_publication_state(target_plan_id uuid)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare plan_is_ready boolean := false;
begin
  select exists (
    select 1 from public.timetable_slots slot
    join public.weekly_plans plan on plan.class_id = slot.class_id
    where plan.id = target_plan_id and slot.requires_weekly_plan_submission
  ) and not exists (
    select 1 from public.timetable_slots slot
    join public.weekly_plans plan on plan.class_id = slot.class_id
    where plan.id = target_plan_id and slot.requires_weekly_plan_submission
      and not exists (
        select 1 from public.plan_entries entry
        where entry.weekly_plan_id = target_plan_id
          and entry.timetable_slot_id = slot.id
          and entry.teacher_id = slot.teacher_id
          and entry.subject_id = slot.subject_id
          and btrim(coalesce(entry.classwork, '')) <> ''
      )
  ) into plan_is_ready;

  update public.weekly_plans
  set status = case when plan_is_ready then 'published' else 'draft' end,
      published_at = case when plan_is_ready then coalesce(published_at, now()) else null end,
      updated_at = now()
  where id = target_plan_id;
  return coalesce(plan_is_ready, false);
end;
$$;

create or replace function private.refresh_publication_after_plan_entry()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'DELETE' then
    perform private.refresh_weekly_plan_publication_state(old.weekly_plan_id);
    return old;
  end if;
  perform private.refresh_weekly_plan_publication_state(new.weekly_plan_id);
  return new;
end;
$$;

drop trigger if exists refresh_publication_after_plan_entry on public.plan_entries;
create trigger refresh_publication_after_plan_entry
after insert or update or delete on public.plan_entries
for each row execute function private.refresh_publication_after_plan_entry();

