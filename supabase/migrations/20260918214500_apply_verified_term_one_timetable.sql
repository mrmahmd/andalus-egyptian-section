-- Fail atomically if an expected staff account is not active.
do $$
declare missing_usernames text;
begin
  select string_agg(map.username, ', ' order by map.username)
  into missing_usernames
  from verified_teacher_usernames map
  left join public.profiles profile on profile.username = map.username and profile.status = 'active'
  where profile.user_id is null;
  if missing_usernames is not null then
    raise exception 'Missing active teacher accounts: %', missing_usernames;
  end if;
end $$;

